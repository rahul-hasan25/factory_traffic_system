from django.db import models

from apps.traffic_control.domain.safety import Direction
from apps.traffic_control.domain.scheduler import VehicleType
from .junction import Junction


class SensorEventType(models.TextChoices):
    VEHICLE_ARRIVED = "VEHICLE_ARRIVED", "VEHICLE_ARRIVED"
    VEHICLE_CLEARED = "VEHICLE_CLEARED", "VEHICLE_CLEARED"


class SensorEvent(models.Model):
    """
    Stores sensor telemetry events.
    Key purposes:
      1. Idempotency: Processing the same event_id more than once will be rejected/ignored.
      2. Audit & Sequence: Tracks sensor sequence_no and timing anomalies (delayed/out-of-order).
    """

    # Idempotency identifier: Ensures duplicate payloads are rejected at DB level
    event_id = models.CharField(
        max_length=100,
        primary_key=True,
        help_text="Unique event UUID/string sent by the edge sensor (e.g., 'evt-10001')",
    )

    # Relation to targeted Junction (e.g., Junction A)
    junction = models.ForeignKey(
        Junction,
        on_delete=models.CASCADE,
        related_name="sensor_events",
        help_text="Target junction intersection",
    )

    # Direction from which sensor fired: NORTH, SOUTH, EAST, WEST
    direction = models.CharField(
        max_length=10,
        choices=[(d.value, d.value) for d in Direction],
        db_index=True,
        help_text="Direction approach where vehicle was detected",
    )

    # Type of event: VEHICLE_ARRIVED or VEHICLE_CLEARED
    event_type = models.CharField(
        max_length=30,
        choices=SensorEventType.choices,
        help_text="Lifecycle state of the vehicle at the sensor",
    )

    # Physical vehicle identifier (e.g., 'VH-501')
    vehicle_id = models.CharField(
        max_length=50,
        db_index=True,
        help_text="Unique registration/tag of vehicle",
    )

    # Priority classification: EMERGENCY > TRUCK > FORKLIFT > EMPLOYEE_VEHICLE
    vehicle_type = models.CharField(
        max_length=30,
        choices=[(v.value, v.value) for v in VehicleType],
        default=VehicleType.EMPLOYEE_VEHICLE.value,
        help_text="Classification determining scheduling priority weight",
    )

    # Monotonically increasing counter generated by physical sensor
    sequence_no = models.BigIntegerField(
        null=True,
        blank=True,
        help_text="Sensor-generated sequence number to detect out-of-order packets",
    )

    # Sensor reported time vs server ingestion time
    sensor_timestamp = models.DateTimeField(
        help_text="Time recorded by the edge sensor device",
    )
    received_at = models.DateTimeField(
        auto_now_add=True,
        db_index=True,
        help_text="Time when the backend API successfully ingested the event",
    )

    # Processing metadata
    is_processed = models.BooleanField(
        default=False,
        help_text="Flag indicating whether event successfully modified the traffic queue",
    )
    processing_notes = models.CharField(
        max_length=255,
        null=True,
        blank=True,
        help_text="Notes for anomalies like out-of-order, delayed, or duplicate re-submission",
    )

    class Meta:
        db_table = "traffic_sensor_events"
        verbose_name = "Sensor Event"
        verbose_name_plural = "Sensor Events"
        ordering = ["-received_at"]
        indexes = [
            models.Index(fields=["junction", "direction", "event_type"]),
            models.Index(fields=["vehicle_id", "sensor_timestamp"]),
        ]

    def __str__(self) -> str:
        return f"{self.event_id} | {self.event_type} | {self.vehicle_id} ({self.direction})"